# while loop examples

# count from 1 to 10
i = 0
while i < 10:
    i+=1
    print(i)

# sum of numbers from 1 to 10
j = 1
sum = 0
while j <= 10:
    sum += j
    j+=1
    print(j)


# print even numbers under 10
k = 2
while k < 10:
    print(k)
    k += 2

# reverse count
l = 5
while l > 0:
    print(l)
    l -= 1
