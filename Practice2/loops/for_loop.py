# basic for loop examples

# print each fruit in fruit list
fruits = ["apple", "banana", "cherry"]
for x in fruits:
  print(x)

# looping through a string
for x in "banana":
  print(x)

# using range()
for i in range(5):
    print(i)

# range with step
for j in range(1, 2, 8):
   print(j)

# nested for loop
for i in range(3):
    for j in range(2):
        print(i, j)
